#!/usr/bin/env python3
"""Build the eesky-combat-lab plugin from fights.txt.

Reads eesky/combat-lab/fights.txt, checks every ship name against the game
data, refreshes the list of ship models at the bottom of fights.txt, and
writes the plugin to eesky/plugins/eesky-combat-lab. Each fight becomes a
start scenario in the game's New Pilot screen.

Usage: eesky/combat-lab/build.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIGHTS = ROOT / "eesky" / "combat-lab" / "fights.txt"
PLUGIN = ROOT / "eesky" / "plugins" / "eesky-combat-lab"
LIST_MARKER = "# --- Ship models"
DEFAULT_DISTANCE = 1500

SHIP_RE = re.compile(r'^ship (?:"([^"]+)"|`([^`]+)`|(\S+))\s*$')
CATEGORY_RE = re.compile(r'^\t\tcategory "([^"]+)"')
THUMBNAIL_RE = re.compile(r'^\tthumbnail (?:"([^"]+)"|(\S+))')


def load_ships():
	"""Return {model name: (category, faction folder, thumbnail)} for every base ship model."""
	ships = {}
	for path in sorted((ROOT / "data").rglob("*.txt")):
		folder = path.relative_to(ROOT / "data").parts[0] if path.parent != ROOT / "data" else "misc"
		if folder == "_deprecated":
			continue
		lines = path.read_text(encoding="utf-8", errors="replace").split("\n")
		for i, line in enumerate(lines):
			match = SHIP_RE.match(line)
			if not match:
				continue
			name = next(group for group in match.groups() if group)
			category = thumbnail = None
			for child in lines[i + 1:]:
				if child and not child.startswith("\t"):
					break
				if not category and (found := CATEGORY_RE.match(child)):
					category = found.group(1)
				if not thumbnail and (found := THUMBNAIL_RE.match(child)):
					thumbnail = found.group(1) or found.group(2)
			if category and name not in ships:
				ships[name] = (category, folder, thumbnail)
	return ships


def tokenize(line):
	"""Split one data-file line into tokens, honoring quotes and backticks."""
	return [a or b or c for a, b, c in re.findall(r'"([^"]*)"|`([^`]*)`|(\S+)', line)]


def load_fights(text, ships):
	"""Parse fight blocks. Returns (fights, errors)."""
	fights, errors = [], []
	current = None
	for number, raw in enumerate(text.split("\n"), 1):
		if raw.startswith(LIST_MARKER):
			break
		line = raw.split("#", 1)[0].rstrip()
		if not line.strip():
			continue
		tokens = tokenize(line)
		if not raw.startswith("\t"):
			if tokens[0] != "fight" or len(tokens) != 2:
				errors.append(f"line {number}: expected `fight \"<name>\"`, got: {raw.strip()}")
				current = None
				continue
			current = {"name": tokens[1], "line": number, "distance": DEFAULT_DISTANCE}
			fights.append(current)
		elif current is None:
			errors.append(f"line {number}: indented line outside a fight")
		elif tokens[0] in ("player", "enemy") and len(tokens) == 2:
			if tokens[1] not in ships:
				errors.append(f"line {number}: unknown ship model \"{tokens[1]}\" (see the list at the bottom)")
			current[tokens[0]] = tokens[1]
		elif tokens[0] == "distance" and len(tokens) == 2 and tokens[1].isdigit():
			current["distance"] = int(tokens[1])
		else:
			errors.append(f"line {number}: unrecognized line: {raw.strip()}")

	names = set()
	for fight in fights:
		for key in ("player", "enemy"):
			if key not in fight:
				errors.append(f"line {fight['line']}: fight \"{fight['name']}\" has no {key} ship")
		if fight["name"] in names:
			errors.append(f"line {fight['line']}: two fights are named \"{fight['name']}\"")
		names.add(fight["name"])
	return fights, errors


def ship_list(ships):
	"""The commented-out list of ship models, grouped by faction."""
	lines = [LIST_MARKER + " (rewritten by build.py; edits below this line are lost) ---"]
	for folder in sorted({folder for _, folder, _ in ships.values()}):
		lines.append("#")
		lines.append(f"# {folder.title()}")
		for name in sorted(name for name, (_, f, _) in ships.items() if f == folder):
			lines.append(f"#   {name} ({ships[name][0]})")
	return "\n".join(lines) + "\n"


def quote(text):
	return f"`{text}`" if '"' in text else f'"{text}"'


def plugin_data(fights, ships):
	out = [
		"# Generated by eesky/combat-lab/build.py from eesky/combat-lab/fights.txt. Do not edit.",
		"",
		'government "eesky: Combat Lab Opponent"',
		"\tcolor .85 .25 .2",
		'\t"player reputation" -1000',
		'\t"bribe" 0',
		'\t"fine" 0',
		"",
		'system "eesky: Combat Lab"',
		"\tpos -1400 -1100",
		"\tgovernment Uninhabited",
		"\thabitable 0",
		'\tobject "eesky: Combat Lab Station"',
		"\t\tsprite planet/station0",
		"\t\tdistance 4000",
		"\t\tperiod 100000",
		"",
		'planet "eesky: Combat Lab Station"',
		"\tlandscape land/station0",
		"\tdescription `A bare practice station far from any shipping lane. Take off to start the duel. "
		"Each round ends the moment either ship is disabled or destroyed; both ships are then repaired, "
		"rearmed, and set facing each other again.`",
		"",
		'conversation "eesky: combat lab intro"',
		"\t`Welcome to the Combat Lab. Take off to start the duel; it restarts on its own every time a ship goes down.`",
		"\tname",
		"",
	]
	for fight in fights:
		model = fight["player"]
		condition = f"eesky: combat lab: {fight['name']}"
		thumbnail = ships[model][2]
		out += [
			"",
			f"start {quote(condition)}",
			f"\tname {quote('Combat Lab: ' + fight['name'])}",
			f"\tdescription `{model} ({ships[model][0]}) against {fight['enemy']} ({ships[fight['enemy']][0]}), "
			f"both with stock outfits, starting {fight['distance']} apart.`",
		]
		if thumbnail:
			out.append(f"\tthumbnail {quote(thumbnail)}")
		out += [
			"\tdate 16 11 3013",
			'\tsystem "eesky: Combat Lab"',
			'\tplanet "eesky: Combat Lab Station"',
			'\tconversation "eesky: combat lab intro"',
			f"\tship {quote(model)} {quote(model)}",
			'\tset "arena: active"',
			f'\t"arena: distance" = {fight["distance"]}',
			f"\tset {quote(condition)}",
			"",
			f"mission {quote(condition)}",
			"\tinvisible",
			"\tlanding",
			"\tto offer",
			f"\t\thas {quote(condition)}",
			"\tnpc",
			'\t\tgovernment "eesky: Combat Lab Opponent"',
			"\t\tpersonality heroic nemesis staying",
			f"\t\tship {quote(fight['enemy'])} {quote(fight['enemy'])}",
		]
	return "\n".join(out) + "\n"


def main():
	ships = load_ships()
	text = FIGHTS.read_text(encoding="utf-8")
	fights, errors = load_fights(text, ships)
	if errors:
		print("fights.txt has errors:", *errors, sep="\n  ", file=sys.stderr)
		return 1
	if not fights:
		print("fights.txt defines no fights.", file=sys.stderr)
		return 1

	# Refresh the ship list at the bottom of fights.txt.
	head = text.split(LIST_MARKER, 1)[0].rstrip("\n")
	FIGHTS.write_text(head + "\n\n\n" + ship_list(ships), encoding="utf-8")

	(PLUGIN / "data").mkdir(parents=True, exist_ok=True)
	(PLUGIN / "plugin.txt").write_text(
		'name "eesky-combat-lab"\n'
		'about "One-on-one practice duels that restart the moment either ship goes down. '
		'Pick a fight from the New Pilot screen. Generated from eesky/combat-lab/fights.txt."\n'
		'version "0.1.0"\n'
		"authors\n"
		'\t"Logan Weir"\n'
		"tags\n"
		'\t"combat"\n', encoding="utf-8")
	(PLUGIN / "data" / "combat lab.txt").write_text(plugin_data(fights, ships), encoding="utf-8")
	print(f"Wrote {len(fights)} fights to {PLUGIN.relative_to(ROOT)}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
